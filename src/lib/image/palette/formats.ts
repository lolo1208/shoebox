/**
 * 调色板导出格式。
 *
 * 每个格式只负责把 PaletteColor[] 序列化为文本，复制与下载交给 UI，
 * 新增格式时在这里追加一项即可。
 */

import { formatHsl, formatOklch, formatRgb } from './color';
import type { PaletteColor } from './extract';

export interface PaletteFormatOptions {
  /** CSS 变量 / Tailwind 键名前缀 */
  prefix: string;
  uppercase: boolean;
}

export const DEFAULT_FORMAT_OPTIONS: PaletteFormatOptions = {
  prefix: 'color',
  uppercase: false,
};

export interface PaletteFormat {
  id: string;
  /** 文案 key（palette.fmt.*） */
  labelKey: string;
  extension: string;
  mime: string;
  build: (colors: PaletteColor[], options: PaletteFormatOptions) => string;
}

const share = (value: number): string => `${(value * 100).toFixed(1)}%`;
const nameOf = (prefix: string, index: number): string => `${prefix}-${index + 1}`;
const asHex = (color: PaletteColor, options: PaletteFormatOptions): string =>
  options.uppercase ? color.hex.toUpperCase() : color.hex;

const css = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  [
    '/* Palette generated by LOLO\' Shoebox */',
    ':root {',
    ...colors.map(
      (color, index) =>
        `  --${nameOf(options.prefix, index)}: ${asHex(color, options)}; /* ${share(color.share)} */`,
    ),
    '}',
    '',
  ].join('\n');

const scss = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  [
    '// Palette generated by LOLO\' Shoebox',
    ...colors.map(
      (color, index) =>
        `$${nameOf(options.prefix, index)}: ${asHex(color, options)}; // ${share(color.share)}`,
    ),
    '',
  ].join('\n');

const tailwind = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  [
    '// tailwind.config.js — palette generated by LOLO\' Shoebox',
    'module.exports = {',
    '  theme: {',
    '    extend: {',
    '      colors: {',
    `        ${options.prefix}: {`,
    // 按 Tailwind 习惯使用 100/200/300… 色阶键名
    ...colors.map(
      (color, index) =>
        `          ${(index + 1) * 100}: '${asHex(color, options)}', // ${share(color.share)}`,
    ),
    '        },',
    '      },',
    '    },',
    '  },',
    '};',
    '',
  ].join('\n');

const json = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  `${JSON.stringify(
    colors.map((color, index) => ({
      name: nameOf(options.prefix, index),
      hex: asHex(color, options),
      rgb: [color.rgb.r, color.rgb.g, color.rgb.b],
      hsl: [Math.round(color.hsl.h), Math.round(color.hsl.s * 100), Math.round(color.hsl.l * 100)],
      oklch: [
        Number((color.oklch.l * 100).toFixed(1)),
        Number(color.oklch.c.toFixed(3)),
        Number(color.oklch.h.toFixed(1)),
      ],
      // share 为 0–1 比例，percent 为可读百分比
      share: Number(color.share.toFixed(4)),
      percent: share(color.share),
    })),
    null,
    2,
  )}\n`;

const hexList = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  `${colors.map(color => asHex(color, options)).join(', ')}\n`;

const gpl = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  [
    'GIMP Palette',
    `Name: ${options.prefix} palette`,
    `Columns: ${Math.min(8, colors.length)}`,
    '#',
    ...colors.map(
      (color, index) =>
        `${color.rgb.r}\t${color.rgb.g}\t${color.rgb.b}\t${nameOf(options.prefix, index)} (${share(color.share)})`,
    ),
    '',
  ].join('\n');

const csv = (colors: PaletteColor[], options: PaletteFormatOptions): string =>
  [
    'name,hex,r,g,b,h,s,l,share',
    ...colors.map((color, index) =>
      [
        nameOf(options.prefix, index),
        asHex(color, options),
        color.rgb.r,
        color.rgb.g,
        color.rgb.b,
        Math.round(color.hsl.h),
        `${Math.round(color.hsl.s * 100)}%`,
        `${Math.round(color.hsl.l * 100)}%`,
        share(color.share),
      ].join(','),
    ),
    '',
  ].join('\n');

const svg = (colors: PaletteColor[], options: PaletteFormatOptions): string => {
  const cell = 160;
  const swatchHeight = 160;
  const labelHeight = 64;
  const width = Math.max(1, colors.length) * cell;
  const height = swatchHeight + labelHeight;

  const cells = colors
    .map((color, index) => {
      const x = index * cell;
      return [
        `  <rect x="${x}" y="0" width="${cell}" height="${swatchHeight}" fill="${asHex(color, options)}"/>`,
        `  <text x="${x + cell / 2}" y="${swatchHeight + 28}" text-anchor="middle" font-family="ui-monospace, Menlo, monospace" font-size="20" fill="#1c1f23">${asHex(color, options)}</text>`,
        `  <text x="${x + cell / 2}" y="${swatchHeight + 50}" text-anchor="middle" font-family="ui-monospace, Menlo, monospace" font-size="15" fill="#888d92">${share(color.share)}</text>`,
      ].join('\n');
    })
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
    '  <rect width="100%" height="100%" fill="#ffffff"/>',
    cells,
    '</svg>',
    '',
  ].join('\n');
};

const plainText = (colors: PaletteColor[]): string =>
  [
    'Palette — LOLO\' Shoebox',
    ...colors.map(
      (color, index) =>
        `${String(index + 1).padStart(2, '0')}  ${color.hex}  ${formatRgb(color.rgb)}  ${formatHsl(color.hsl)}  ${formatOklch(color.oklch)}  ${share(color.share)}`,
    ),
    '',
  ].join('\n');

export const PALETTE_FORMATS: PaletteFormat[] = [
  { id: 'css', labelKey: 'palette.fmt.css', extension: 'css', mime: 'text/css', build: css },
  { id: 'tailwind', labelKey: 'palette.fmt.tailwind', extension: 'js', mime: 'text/javascript', build: tailwind },
  { id: 'json', labelKey: 'palette.fmt.json', extension: 'json', mime: 'application/json', build: json },
  { id: 'scss', labelKey: 'palette.fmt.scss', extension: 'scss', mime: 'text/x-scss', build: scss },
  { id: 'hex', labelKey: 'palette.fmt.hex', extension: 'txt', mime: 'text/plain', build: hexList },
  { id: 'gpl', labelKey: 'palette.fmt.gpl', extension: 'gpl', mime: 'text/plain', build: gpl },
  { id: 'svg', labelKey: 'palette.fmt.svg', extension: 'svg', mime: 'image/svg+xml', build: svg },
  { id: 'csv', labelKey: 'palette.fmt.csv', extension: 'csv', mime: 'text/csv', build: csv },
  { id: 'text', labelKey: 'palette.fmt.text', extension: 'txt', mime: 'text/plain', build: colors => plainText(colors) },
];

export const buildPaletteText = (
  formatId: string,
  colors: PaletteColor[],
  options: PaletteFormatOptions = DEFAULT_FORMAT_OPTIONS,
): string => {
  const format = PALETTE_FORMATS.find(item => item.id === formatId) || PALETTE_FORMATS[0];
  return format.build(colors, options);
};
